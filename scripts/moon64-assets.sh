#!/usr/bin/env bash
# moon64-assets.sh <SLSsteam.so> <outdir> [release tag] — emit the release assets the moon64
# switcher gates a prebuilt on, next to a copy of the library:
#
#   <outdir>/SLSsteam.so          the library, verbatim
#   <outdir>/SLSsteam.so.sha256   "<sha256>  SLSsteam.so"
#   <outdir>/pattern-status.txt   res/pattern-status.counts plus one
#                                 binary_sha256= line naming this exact library
#                                 and one source_commit= line naming the commit
#                                 and one release_tag= line naming the release
#                                 this library ships in (moon64's About stamp
#                                 for the fork's tab reads it)
#
# moon64/install.sh downloads SLSsteam.so and pattern-status.txt, then refuses
# the pair unless the status file names the downloaded library by sha256 and
# reports a complete table (arch=x86_64, resolved=required, pending=0,
# runipcframe_tail=ready). This script fails closed: it refuses to emit a
# status file whose committed counts would not pass that gate, so a release
# with a broken table fails in CI instead of at the user's machine.
#
# No netsock64 assets: moon64 builds netsock64.so locally from its own patches.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
COUNTS="$REPO_ROOT/res/pattern-status.counts"

die() { echo "moon64-assets: $*" >&2; exit 1; }

[ $# -ge 2 ] && [ $# -le 3 ] || die "usage: $0 <SLSsteam.so> <outdir> [release tag]"
so="$1" outdir="$2"

[ -f "$so" ] || die "no such library: $so"
[ -f "$COUNTS" ] || die "committed counts missing: $COUNTS"
file -b "$so" | grep -q 'ELF 64-bit LSB shared object, x86-64' \
	|| die "$so is not a 64-bit x86-64 shared object"

# Same keys the moon64 gate requires, each exactly once, with gate-passing
# values; read from the committed counts so CI fails when the table regresses.
declare -A seen=()
arch="" required="" resolved="" pending="" tail_state=""
while IFS= read -r line || [ -n "$line" ]; do
	line="${line%$'\r'}"
	case "${line#"${line%%[![:space:]]*}"}" in
		''|'#'*) continue ;;
		*=*)
			key="${line%%=*}"
			key="${key#"${key%%[![:space:]]*}"}"
			val="${line#*=}"
			seen[$key]=$(( ${seen[$key]:-0} + 1 ))
			case "$key" in
				arch) arch="$val" ;;
				required) required="$val" ;;
				resolved) resolved="$val" ;;
				pending) pending="$val" ;;
				runipcframe_tail) tail_state="$val" ;;
			esac ;;
	esac
done < "$COUNTS"

is_uint() { [ -n "$1" ] && [ -z "${1//[0-9]/}" ]; }

[ "${seen[arch]:-0}" -eq 1 ] && [ "$arch" = x86_64 ] \
	|| die "counts: need exactly one arch=x86_64 line"
[ "${seen[required]:-0}" -eq 1 ] && is_uint "$required" && [ "$((10#$required))" -ge 1 ] \
	|| die "counts: need exactly one required=<n>=1 line"
[ "${seen[resolved]:-0}" -eq 1 ] && is_uint "$resolved" \
	|| die "counts: need exactly one resolved=<n> line"
[ "$resolved" = "$required" ] \
	|| die "counts: resolved=$resolved != required=$required (table incomplete)"
[ "${seen[pending]:-0}" -eq 1 ] && [ "$pending" = 0 ] \
	|| die "counts: need exactly one pending=0 line"
[ "${seen[runipcframe_tail]:-0}" -eq 1 ] && [ "$tail_state" = ready ] \
	|| die "counts: need exactly one runipcframe_tail=ready line"

sha="$(sha256sum "$so" | cut -d' ' -f1)"
commit="$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
tag="${3:-$(git -C "$REPO_ROOT" describe --tags --exact-match HEAD 2>/dev/null || true)}"
[ -n "$tag" ] || die "release tag unknown: pass it as the third argument (the release this library ships in)"

mkdir -p "$outdir"
install -m 644 "$so" "$outdir/SLSsteam.so"
printf '%s  %s\n' "$sha" SLSsteam.so > "$outdir/SLSsteam.so.sha256"
{
	echo "# Measured on the SLSsteam.so named below; generated by scripts/moon64-assets.sh."
	echo "# Counts come from the committed res/pattern-status.counts (offline audit)."
	grep -vE '^\s*(#|$)' "$COUNTS"
	printf 'binary_sha256=%s\n' "$sha"
printf 'source_commit=%s\n' "$commit"
printf 'release_tag=%s\n' "$tag"
} > "$outdir/pattern-status.txt"

echo "moon64-assets: $outdir/{SLSsteam.so,SLSsteam.so.sha256,pattern-status.txt}"
echo "moon64-assets: binary_sha256=$sha source_commit=$commit release_tag=$tag"
